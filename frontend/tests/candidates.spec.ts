import {test,expect} from '@playwright/test'

test('candidate alerts stay partial, missing delivery stays unknown, unresolved symbols can be saved',async({page})=>{
 let saved=false
 await page.route('**/api/v1/session',r=>r.fulfill({json:{authenticated:true}}))
 await page.route('**/api/v1/dashboard',r=>r.fulfill({json:{datasets:[],jobs:[]}}))
 await page.route('**/v1/real-research/**',r=>r.fulfill({status:503,json:{detail:'Test evidence unavailable'}}))
 await page.route('**/v1/real-research/workbench',r=>r.fulfill({json:{rows:[]}}))
 await page.route('**/v1/real-research/watchlist**',r=>{
  if(r.request().method()==='PUT')saved=true
  return r.fulfill({json:{entries:saved?{'CHARTINK:test:TEST':{status:'Researching',note:''}}:{}}})
 })
 await page.route('**/v1/real-research/candidates?*',r=>r.fulfill({json:{rows:[{candidate_id:'fixture',watchlist_key:'CHARTINK:test:TEST',symbol:'TEST',session_date:'2026-11-05',scanner:{scan_name:'Synthetic scanner',version:'1'},source_url:'https://chartink.com',match_status:'first_observed_unverified',completeness:'partial_unverified',timestamp_basis:'receipt_date_unverified_provider_time_only',mode:'synthetic_fixture',research_status:'blocked',research:{status:'blocked',identity_status:'unverified',reasons:['nse_identity_missing_or_ambiguous'],research_priority:'not_rankable'}}],total:1,session_date:'2026-11-05',delivery_status:'observed_partial_or_snapshot',inbox:{completed:1}}}))
 await page.goto('/#real-research')
 const w=page.getByRole('region',{name:'Research workbench',exact:true})
 await w.getByRole('button',{name:'Candidates',exact:true}).click()
 const c=w.getByRole('region',{name:'Scanner candidates'})
 await expect(c).toContainText('partial unverified')
 await expect(c).toContainText('SYNTHETIC FIXTURE')
 await expect(c).toContainText('first observed unverified')
 await expect(c.getByRole('button',{name:'Open TEST research'})).toHaveCount(0)
 await c.getByRole('button',{name:'Save TEST to watchlist'}).click()
 await expect(c).toContainText('Saved to watchlist')
 await expect(w.getByRole('button',{name:'Watchlist (1)'})).toBeVisible()
})

test('stored swing review ranks current evidence and exposes unavailable inputs',async({page})=>{
 await page.route('**/api/v1/session',r=>r.fulfill({json:{authenticated:true}}))
 await page.route('**/api/v1/dashboard',r=>r.fulfill({json:{datasets:[],jobs:[]}}))
 await page.route('**/v1/real-research/**',r=>r.fulfill({status:503,json:{detail:'Test evidence unavailable'}}))
 await page.route('**/v1/real-research/workbench',r=>r.fulfill({json:{rows:[]}}))
 await page.route('**/v1/real-research/watchlist',r=>r.fulfill({json:{entries:{}}}))
 const candidate=(symbol:string)=>({candidate_id:symbol,watchlist_key:'CHARTINK:test:'+symbol,symbol,session_date:'2026-11-13',scanner:{scan_name:'Synthetic scanner',version:'1'},source_url:'https://chartink.com',match_status:'first_observed_unverified',completeness:'partial_unverified',timestamp_basis:'fixture',mode:'synthetic_fixture',research_status:'blocked',research:{status:'blocked',reasons:['recent_sessions_not_ingested']}})
 await page.route('**/v1/real-research/candidates?*',r=>r.fulfill({json:{rows:[],total:0,session_date:null,delivery_status:'missing_delivery_not_verified_zero'}}))
 await page.route('**/v1/real-research/candidates/swing-review?*',r=>{
  expect(r.request().url()).toContain('limit=20')
  return r.fulfill({json:{rows:[{...candidate('CURRENT'),swing_review:{status:'available_descriptive_only',rank:1,price_checks_met:2,checks:{ema_trend:true,price_breakout:true,relative_volume:null},reasons:['not_a_complete_strategy_signal']}},{...candidate('STALE'),swing_review:{status:'unavailable',rank:null,price_checks_met:null,checks:{ema_trend:null,price_breakout:null,relative_volume:null},reasons:['recent_sessions_not_ingested']}}],total:2,session_date:'2026-11-13',delivery_status:'observed_partial_or_snapshot',evaluated_at:'2026-11-13T12:00:00Z',ranking_scope:'displayed_page_only'}})
 })
 await page.goto('/#real-research')
 await page.getByRole('region',{name:'Research workbench',exact:true}).getByRole('button',{name:'Candidates',exact:true}).click()
 const c=page.getByRole('region',{name:'Scanner candidates'})
 await c.getByRole('checkbox',{name:'Review stored swing prices'}).check()
 const ranked=c.getByLabel('Swing price review for CURRENT')
 await expect(ranked).toContainText('Page research rank 1')
 await expect(ranked).toContainText('2 of 2 price checks met')
 await expect(ranked).toContainText('relative volume: Unavailable')
 await expect(c.getByLabel('Swing price review for STALE')).toContainText('Unranked')
 await expect(c.getByLabel('Swing price review for STALE')).toContainText('recent sessions not ingested')
 await expect(c).toContainText('not a full-universe ranking or a BUY signal')
 await c.getByRole('checkbox',{name:'Review stored swing prices'}).uncheck()
 await expect(c.getByLabel('Swing price review for CURRENT')).toHaveCount(0)
})
