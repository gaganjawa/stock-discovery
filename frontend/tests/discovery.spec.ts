import { test, expect } from '@playwright/test'
import { readFileSync, existsSync } from 'node:fs'
const token=process.env.AUTH_TOKEN??(existsSync('../.env')?readFileSync('../.env','utf8').split('\n').find(x=>x.startsWith('AUTH_TOKEN='))?.slice(11):undefined)

test('three horizons, four decisions, research comparison and permission-gated source inspection',async({page})=>{
 test.setTimeout(180000)
 if(!token)throw new Error('Set the local test owner key')
 await page.goto('/')
 await page.getByLabel('Owner access key').fill(token)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 const discovery=page.getByRole('region',{name:'Three-horizon discovery'})
 await expect(discovery).toBeVisible()
 for(const name of ['Swing','Short-term','Long-term']){
  await discovery.getByRole('tab',{name:new RegExp(name)}).click()
  const created=page.waitForResponse(r=>r.url().endsWith('/v1/discovery-runs')&&r.request().method()==='POST')
  await discovery.getByRole('button',{name:'Run fictional discovery',exact:true}).click()
  const run=await (await created).json()
  await expect.poll(async()=>{const response=await page.request.get(run.status_url);return (await response.json()).status},{timeout:60000}).toBe('completed')
  await discovery.getByRole('button',{name:'Refresh discovery'}).click()
  await expect(discovery.getByRole('status')).toHaveAttribute('data-run-id',run.run_id)
  await expect(discovery.getByRole('status')).toContainText('completed',{timeout:60000})
  await expect(discovery.getByRole('region',{name:'Universe coverage'})).toContainText('5 / 5 fictional listings screened')
  const table=discovery.locator('table').first()
  for(const action of ['BUY','WATCH','AVOID','INSUFFICIENT EVIDENCE'])await expect(table.getByText(action,{exact:true}).first()).toBeVisible()
  await expect(table).toContainText('Blocked · no quantity')
 }
 await discovery.getByRole('button',{name:'Inspect SYN-D309-READY',exact:true}).click()
 const detail=discovery.getByRole('region',{name:'Discovery recommendation details'})
 await expect(detail.getByRole('heading',{name:'Research mode comparison'})).toBeVisible()
 await expect(detail).toContainText('Quantitative + RAG')
 await expect(detail).toContainText('Quantitative + agent')
 await expect(detail).toContainText('No purchasable quantity')
 await discovery.getByLabel('Discovery research mode').selectOption('quant_agent')
 await discovery.getByRole('button',{name:'Inspect SYN-D309-READY',exact:true}).click()
 await expect(detail).toContainText('Fictional SYN-D309-READY earnings disclosure')
 await detail.getByRole('button',{name:'Inspect source 1',exact:true}).click()
 await expect(detail.getByRole('region',{name:'Source inspection'})).toContainText('Fictional')
 await page.screenshot({path:'test-results/discovery.png',fullPage:true})
 await discovery.getByRole('button',{name:'Inspect SYN-D309-CONFLICT',exact:true}).click()
 await expect(detail).toContainText('INSUFFICIENT EVIDENCE')
 await expect(detail).toContainText('Conflicting evidence')
 // Revocation errors must remove already visible source text and cached detail.
 await page.route('**/v1/discovery?**',route=>route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({detail:{message:'source permission denied'}})}))
 await discovery.getByRole('button',{name:'Refresh discovery'}).click()
 await expect(discovery.getByRole('alert')).toContainText('source permission denied')
 await expect(detail).toHaveCount(0)
 await page.getByRole('button',{name:'Sign out',exact:true}).click()
 await expect(page.getByLabel('Owner access key')).toBeVisible()
 await expect(discovery).toHaveCount(0)
})
