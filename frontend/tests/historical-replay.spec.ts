import {test,expect} from './fixtures/authenticated'
test('full fictional financial freeze and technical outcome remain distinct',async({page})=>{
 await page.goto('/#dashboard')
 await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible()
 const initialize=page.getByRole('button',{name:'Load synthetic history'})
 if(await initialize.count())await initialize.click()
 await expect(page.getByRole('heading',{name:'Fictional history is ready'})).toBeVisible({timeout:60000})
 await page.getByRole('link',{name:'Replay',exact:true}).click()
 await page.getByLabel('Instrument',{exact:true}).selectOption('SYN-ALPHA')
 await page.getByLabel('Include fictional financial evidence').check()
 await page.getByLabel('Contemporaneous AI run (optional)').fill('UNKNOWN-RUN')
 const request=page.waitForResponse(r=>r.url().endsWith('/api/v1/analysis')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Freeze recommendation'}).click()
 const frozen=await (await request).json()
 expect(frozen.recommendation.action).toBe('INSUFFICIENT_EVIDENCE')
 expect(frozen.recommendation.execution).toBeNull()
 const evidence=page.getByRole('region',{name:'Frozen historical evidence',exact:true})
 await expect(evidence).toContainText('FICTIONAL DEVELOPMENT EVIDENCE')
 await expect(evidence).toContainText('120 INR')
 await expect(evidence).toContainText('No later cached AI report')
 await expect(evidence).toContainText('contemporaneous ai unavailable')
 await expect(page.getByRole('region',{name:'Historical baseline comparison'})).toHaveCount(0)
 const reveal=page.waitForResponse(r=>r.url().endsWith('/reveal'))
 await page.getByRole('button',{name:'Reveal future prices and outcome'}).click()
 const result=await (await reveal).json()
 expect(result.comparison.paired_sample_size).toBe(0)
 expect(result.comparison.baseline.trade).toBeTruthy()
 const comparison=page.getByRole('region',{name:'Historical baseline comparison',exact:true})
 await expect(comparison).toContainText('Subsequent technical baseline outcome')
 await expect(comparison).toContainText('comparison: unavailable')
 const reread=await page.request.get('/api/v1/analysis/'+frozen.recommendation.recommendation_id)
 expect((await reread.json()).historical_snapshot).toEqual(frozen.historical_snapshot)
 await page.getByLabel('Include fictional financial evidence').uncheck()
 await expect(evidence).toHaveCount(0)
 await expect(comparison).toHaveCount(0)
})
