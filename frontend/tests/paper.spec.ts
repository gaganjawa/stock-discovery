import {test,expect} from '@playwright/test'
import {readFileSync,existsSync} from 'node:fs'
const token=process.env.AUTH_TOKEN??(existsSync('../.env')?readFileSync('../.env','utf8').split('\n').find(x=>x.startsWith('AUTH_TOKEN='))?.slice(11):undefined)

test('fictional portfolio reservations, automatic outcomes, drill-down and forward admission block',async({page})=>{
 test.setTimeout(180000)
 if(!token)throw new Error('Set the local test owner key')
 await page.goto('/')
 await page.getByLabel('Owner access key').fill(token)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('region',{name:'Paper portfolio and outcomes'})).toBeVisible()
 // Own immutable batch; no dependence on another browser test's execution order.
 const response=await page.request.post('/v1/discovery-runs',{headers:{'Idempotency-Key':crypto.randomUUID(),'Origin':new URL(page.url()).origin},data:{horizon:'swing'}})
 expect(response.status()).toBe(202)
 const run=await response.json()
 await expect.poll(async()=>(await (await page.request.get(run.status_url)).json()).status,{timeout:60000}).toBe('completed')
 const section=page.getByRole('region',{name:'Paper portfolio and outcomes'})
 await section.getByText('Create a portfolio',{exact:true}).click()
 await section.getByLabel('Portfolio name',{exact:true}).fill('Browser fictional portfolio')
 await section.getByLabel('Virtual starting capital').fill('100000')
 await section.getByRole('button',{name:'Create portfolio',exact:true}).click()
 await expect(section).toContainText('FICTIONAL SIMULATION')
 await section.getByRole('button',{name:'Refresh portfolio',exact:true}).click()
 const option=section.getByLabel('Published recommendation').locator('option').filter({hasText:'SYN-D309-READY'})
 await expect(option).toHaveCount(1)
 await section.getByLabel('Published recommendation').selectOption((await option.getAttribute('value'))!)
 await section.getByRole('button',{name:'Track recommendation',exact:true}).click()
 await expect(section.getByRole('status')).toContainText('admitted: fictional reservation')
 await section.getByRole('button',{name:'Advance one fictional session'}).click()
 await expect(section.getByRole('button',{name:'Advance one fictional session'})).toBeEnabled({timeout:30000})
 await expect(section).toContainText('26/6/2025')
 await section.getByRole('button',{name:'Inspect outcome',exact:true}).click()
 const detail=section.getByRole('region',{name:'Outcome detail'})
 await expect(detail).toContainText('Original BUY')
 await expect(detail.getByRole('heading')).toContainText('SYN-D309-READY')
 await expect(detail).toContainText('Forecast: provisional')
 await expect(section.getByRole('heading',{name:'Performance by horizon',exact:true})).toBeVisible()
 await section.getByText(/Immutable transaction history/).click()
 await expect(section).toContainText('Cash movement')
 await section.screenshot({path:'test-results/paper-portfolio.png'})
 // A separate forward book must not accept this unchanged shadow recommendation.
 await section.getByLabel('Portfolio name',{exact:true}).fill('Browser forward portfolio')
 await section.getByLabel('Portfolio contract').selectOption('forward_paper')
 await section.getByRole('button',{name:'Create portfolio',exact:true}).click()
 await expect(section).toContainText('ACTIVATION BLOCKED')
 await section.getByRole('button',{name:'Track recommendation',exact:true}).click()
 await expect(section.getByRole('status')).toContainText('rejected: mock shadow non actionable')
 await expect(section.getByRole('button',{name:'Advance one fictional session'})).toBeDisabled()
 // Current permission failure clears financial details already on screen.
 await page.route('**/v1/paper-portfolio/PAPER-*',route=>route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({detail:{message:'source permission denied'}})}))
 await section.getByRole('button',{name:'Refresh portfolio',exact:true}).click()
 await expect(section.getByRole('alert')).toContainText('source permission denied')
 await expect(section.getByRole('heading',{name:'Positions and holdings'})).toHaveCount(0)
})
