import {test,expect} from './fixtures/authenticated'
test('saved snapshots reopen without future leakage and evaluate a fictional batch',async({page})=>{
 test.setTimeout(180000)
 await page.goto('/#dashboard')
 const init=page.getByRole('button',{name:'Load synthetic history'})
 if(await init.count())await init.click()
 await expect(page.getByRole('heading',{name:'Fictional history is ready'})).toBeVisible({timeout:60000})
 const dashboard=await (await page.request.get('/api/v1/dashboard')).json()
 const version=dashboard.datasets[0].version
 const info=await (await page.request.get('/api/v1/datasets/'+version)).json()
 const origin=new URL(page.url()).origin
 const response=await page.request.post('/api/v1/analysis',{headers:{Origin:origin},data:{dataset_version:version,instrument_id:'SYN-ALPHA',date:info.default_date,include_financial:true}})
 expect(response.status()).toBe(200)
 const a=await response.json(),rid=a.recommendation.recommendation_id
 await page.request.post('/api/v1/analysis/'+rid+'/reveal',{headers:{Origin:origin},data:{}})
 let saved=page.getByRole('region',{name:'Saved historical research',exact:true})
 await saved.getByLabel('Saved dataset').selectOption(version)
 await saved.getByLabel('Saved instrument').fill('SYN-ALPHA')
 await saved.getByRole('button',{name:'Refresh saved research'}).click()
 await saved.locator(`[data-run-id="${rid}"]`).getByRole('button').click()
 const evidence=page.getByRole('region',{name:'Frozen historical evidence',exact:true})
 await expect(evidence).toContainText('120 INR')
 await expect(page.getByRole('heading',{name:'Prices known at the cutoff'})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Subsequent prices revealed'})).toHaveCount(0)
 await expect(page.locator('.candle-chart')).toHaveAttribute('aria-label','Daily candlestick chart, 40 fictional candles')
 await expect(page.getByText('Historical cutoff: '+a.recommendation.information_cutoff_at,{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'Reveal future prices and outcome'}).click()
 await expect(page.getByRole('region',{name:'Historical baseline comparison',exact:true})).toContainText('paired sample size 0')
 const reread=await (await page.request.get('/api/v1/analysis/'+rid)).json()
 expect(reread.historical_snapshot).toEqual(a.historical_snapshot)
 await page.route('**/api/v1/analysis/'+rid,r=>r.fulfill({status:403,json:{detail:'PRIVATE ERROR MUST NOT RENDER'}}))
 saved=page.getByRole('region',{name:'Saved historical research',exact:true})
 await saved.getByLabel('Saved instrument').fill('SYN-ALPHA')
 await saved.locator(`[data-run-id="${rid}"]`).getByRole('button').click()
 await expect(saved.getByRole('alert')).toHaveText('Saved evidence is restricted.')
 await expect(evidence).toHaveCount(0);await expect(page.locator('canvas')).toHaveCount(0)
 await expect(page.getByText('PRIVATE ERROR MUST NOT RENDER')).toHaveCount(0)
 await page.unroute('**/api/v1/analysis/'+rid)
 await saved.getByLabel('Saved dataset').selectOption(version)
 const batch=page.waitForResponse(r=>r.url().endsWith('/api/v1/experiments')&&r.request().method()==='POST')
 await saved.getByRole('button',{name:'Evaluate fictional evidence batch'}).click()
 const jobs=(await (await batch).json()).job_ids
 expect(jobs).toHaveLength(9)
 await expect(saved.getByRole('status')).toContainText('9 fictional replay jobs queued')
 await expect.poll(async()=>Promise.all(jobs.map(async(id:string)=>(await (await page.request.get('/api/v1/jobs/'+id)).json()).status)),{timeout:90000}).toEqual(Array(9).fill('completed'))
 await saved.getByRole('button',{name:'Refresh saved research'}).click()
 await expect(saved).toContainText('eligible paired samples 0')
 await expect(saved).toContainText('unqualified combined')
})
